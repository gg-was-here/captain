// Embeds packages/app-template into the builder bot so its sandbox snapshot can
// be prepared without reading the repo at runtime. Run after editing the template:
//   node scripts/sync-template.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const templateDir = join(root, "packages/app-template");
const skip = new Set(["node_modules", "dist", "package-lock.json"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    if (skip.has(name)) return [];
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = Object.fromEntries(
  walk(templateDir).map((path) => [relative(templateDir, path), readFileSync(path, "utf8")]),
);
const out = join(root, "agents/builder/agent/lib/template-files.ts");
writeFileSync(
  out,
  `// Generated by scripts/sync-template.mjs — do not edit.\nexport const TEMPLATE_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`,
);
console.log(`Wrote ${Object.keys(files).length} template files to ${relative(root, out)}`);
